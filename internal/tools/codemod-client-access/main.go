// codemod-client-access rewrites internal/services production Go files to access per-service
// clients, ResourceManagerAccount, UserFeatures, and StopContext via lightweight Provider
// interfaces instead of importing the monolithic internal/clients package.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"io/fs"
	"os"
	"path/filepath"
	"runtime"
	"sort"
	"strings"
	"sync"
	"sync/atomic"
)

const (
	modulePrefix = "github.com/hashicorp/terraform-provider-azurerm/"
	clientsImp   = modulePrefix + "internal/clients"
	accountImp   = modulePrefix + "internal/clients/account"
	featuresImp  = modulePrefix + "internal/features"
)

type FieldMapping struct {
	FieldName        string `json:"field_name"`
	HelperFuncName   string `json:"helper_func_name"`
	TargetImportPath string `json:"target_import_path"`
	TargetPkgName    string `json:"target_pkg_name"`
}

type textEdit struct {
	start int
	end   int
	repl  string
}

func main() {
	mappingsJSON := flag.String("mappings", "", "path to JSON file generated by generator-client-providers -dump-json")
	targetPath := flag.String("path", "internal/services", "directory to rewrite")

	flag.Parse()

	if *mappingsJSON == "" {
		fmt.Fprintln(os.Stderr, "codemod-client-access: -mappings is required")
		os.Exit(1)
	}

	raw, err := os.ReadFile(*mappingsJSON)
	if err != nil {
		fmt.Fprintf(os.Stderr, "reading mappings: %v\n", err)
		os.Exit(1)
	}

	var list []FieldMapping
	if err := json.Unmarshal(raw, &list); err != nil {
		fmt.Fprintf(os.Stderr, "parsing mappings: %v\n", err)
		os.Exit(1)
	}

	fieldMap := make(map[string]FieldMapping, len(list)+3)
	for _, m := range list {
		fieldMap[m.FieldName] = m
	}

	fieldMap["Account"] = FieldMapping{
		FieldName:        "Account",
		HelperFuncName:   "From",
		TargetImportPath: accountImp,
		TargetPkgName:    "account",
	}
	fieldMap["StopContext"] = FieldMapping{
		FieldName:        "StopContext",
		HelperFuncName:   "StopContext",
		TargetImportPath: accountImp,
		TargetPkgName:    "account",
	}
	fieldMap["Features"] = FieldMapping{
		FieldName:        "Features",
		HelperFuncName:   "From",
		TargetImportPath: featuresImp,
		TargetPkgName:    "features",
	}

	var files []string

	err = filepath.WalkDir(*targetPath, func(p string, d fs.DirEntry, walkErr error) error {
		if walkErr != nil {
			return walkErr
		}

		if d.IsDir() {
			base := d.Name()
			if base == "testdata" || base == "client" || strings.HasPrefix(base, ".") {
				return filepath.SkipDir
			}

			return nil
		}

		name := d.Name()
		if !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") || strings.HasSuffix(name, "provider_gen.go") {
			return nil
		}

		files = append(files, p)

		return nil
	})
	if err != nil {
		fmt.Fprintf(os.Stderr, "walking %s: %v\n", *targetPath, err)
		os.Exit(1)
	}

	var (
		modifiedCount atomic.Int64
		errCount      atomic.Int64
	)

	ch := make(chan string, len(files))
	for _, f := range files {
		ch <- f
	}

	close(ch)

	workers := runtime.NumCPU()

	var wg sync.WaitGroup
	wg.Add(workers)

	for range workers {
		go func() {
			defer wg.Done()

			for filePath := range ch {
				changed, err := processFile(filePath, fieldMap)
				if err != nil {
					fmt.Fprintf(os.Stderr, "error processing %s: %v\n", filePath, err)
					errCount.Add(1)

					continue
				}

				if changed {
					modifiedCount.Add(1)
				}
			}
		}()
	}

	wg.Wait()

	fmt.Printf("codemod-client-access: updated %d files (errors: %d)\n", modifiedCount.Load(), errCount.Load())

	if errCount.Load() > 0 {
		os.Exit(1)
	}
}

func processFile(filePath string, fieldMap map[string]FieldMapping) (bool, error) {
	src, err := os.ReadFile(filePath)
	if err != nil {
		return false, err
	}

	// Quick pre-filter: skip files that neither import internal/clients nor mention .Client.
	if !bytes.Contains(src, []byte("internal/clients")) && !bytes.Contains(src, []byte(".Client.")) {
		return false, nil
	}

	fset := token.NewFileSet()

	file, err := parser.ParseFile(fset, filePath, src, parser.ParseComments)
	if err != nil {
		return false, err
	}

	offset := func(pos token.Pos) int {
		return fset.Position(pos).Offset
	}
	slice := func(start, end token.Pos) string {
		return string(src[offset(start):offset(end)])
	}

	// Map existing imports
	existingPathToAlias := make(map[string]string)
	existingPathToSpec := make(map[string]*ast.ImportSpec)
	existingUsedNames := make(map[string]string) // effectivePkgIdent -> importPath
	clientsPkgIdent := ""

	var clientsImpSpec *ast.ImportSpec

	for _, imp := range file.Imports {
		p := strings.Trim(imp.Path.Value, `"`)

		eff := filepath.Base(p)
		if imp.Name != nil {
			eff = imp.Name.Name
		}

		existingPathToAlias[p] = eff
		existingPathToSpec[p] = imp

		existingUsedNames[eff] = p
		if p == clientsImp {
			clientsPkgIdent = eff
			clientsImpSpec = imp
		}
	}

	// Collect all declared variable/param/type/const names in the file so we know
	// when a package name like "client" or "account" would collide with a local declaration.
	declaredNames := collectDeclaredNames(file)

	isClientsClientType := func(expr ast.Expr) bool {
		if clientsPkgIdent == "" {
			return false
		}

		star, ok := expr.(*ast.StarExpr)
		if !ok {
			return false
		}

		sel, ok := star.X.(*ast.SelectorExpr)
		if !ok {
			return false
		}

		id, ok := sel.X.(*ast.Ident)

		return ok && id.Name == clientsPkgIdent && sel.Sel.Name == "Client"
	}

	var edits []textEdit

	replacedNodes := make(map[ast.Node]bool)

	// Choose an import alias for a needed import path
	neededImports := make(map[string]string) // importPath -> chosenAlias ("" means unaliased)
	pkgIdentFor := func(impPath, defaultPkgName string) string {
		if existingEff, ok := existingPathToAlias[impPath]; ok {
			if spec := existingPathToSpec[impPath]; spec != nil && spec.Name == nil && declaredNames[existingEff] {
				// Existing unaliased import shares a name with a local declaration in this file;
				// alias it now so new calls emitted after `client := ...` cannot be shadowed.
				baseAlias := deriveAlias(impPath, defaultPkgName)
				newAlias := baseAlias

				idx := 2
				for existingUsedNames[newAlias] != "" || declaredNames[newAlias] {
					newAlias = fmt.Sprintf("%s%d", baseAlias, idx)
					idx++
				}

				edits = append(edits, textEdit{
					start: offset(spec.Pos()),
					end:   offset(spec.End()),
					repl:  fmt.Sprintf("%s %s", newAlias, spec.Path.Value),
				})
				replacedNodes[spec] = true

				ast.Inspect(file, func(n ast.Node) bool {
					sel, ok := n.(*ast.SelectorExpr)
					if !ok {
						return true
					}

					id, ok := sel.X.(*ast.Ident)
					if ok && id.Name == existingEff && id.Obj == nil && !replacedNodes[id] {
						edits = append(edits, textEdit{
							start: offset(id.Pos()),
							end:   offset(id.End()),
							repl:  newAlias,
						})
						replacedNodes[id] = true
					}

					return true
				})

				existingPathToAlias[impPath] = newAlias
				existingUsedNames[newAlias] = impPath

				return newAlias
			}

			return existingEff
		}

		if chosen, ok := neededImports[impPath]; ok {
			if chosen == "" {
				return defaultPkgName
			}

			return chosen
		}
		// Check if defaultPkgName collides with another import or a declared name in the file
		_, impCollision := existingUsedNames[defaultPkgName]
		if !impCollision && !declaredNames[defaultPkgName] {
			existingUsedNames[defaultPkgName] = impPath
			neededImports[impPath] = ""

			return defaultPkgName
		}

		baseAlias := deriveAlias(impPath, defaultPkgName)
		alias := baseAlias

		idx := 2
		for existingUsedNames[alias] != "" || declaredNames[alias] {
			alias = fmt.Sprintf("%s%d", baseAlias, idx)
			idx++
		}

		existingUsedNames[alias] = impPath
		neededImports[impPath] = alias

		return alias
	}

	// Rewrite `*clients.ResourceManagerAccount` / `clients.ResourceManagerAccount`
	if clientsPkgIdent != "" {
		ast.Inspect(file, func(n ast.Node) bool {
			sel, ok := n.(*ast.SelectorExpr)
			if !ok {
				return true
			}

			id, ok := sel.X.(*ast.Ident)
			if ok && id.Name == clientsPkgIdent && sel.Sel.Name == "ResourceManagerAccount" {
				accIdent := pkgIdentFor(accountImp, "account")
				edits = append(edits, textEdit{
					start: offset(sel.Pos()),
					end:   offset(sel.End()),
					repl:  accIdent + ".ResourceManagerAccount",
				})
				replacedNodes[sel] = true

				return false
			}

			return true
		})
	}

	// Process each function / method declaration and FuncLit
	processFunc := func(ft *ast.FuncType, body *ast.BlockStmt) {
		paramProviders := make(map[string]bool)

		if ft != nil && ft.Params != nil {
			for _, fld := range ft.Params.List {
				if isClientsClientType(fld.Type) {
					edits = append(edits, textEdit{
						start: offset(fld.Type.Pos()),
						end:   offset(fld.Type.End()),
						repl:  "any",
					})

					replacedNodes[fld.Type] = true
					for _, nameIdent := range fld.Names {
						paramProviders[nameIdent.Name] = true
					}
				}
			}
		}

		if body == nil {
			return
		}

		// Find local alias assignments: `v := meta.(*clients.Client)` or `v := metadata.Client`
		type localAlias struct {
			stmt         ast.Stmt
			providerExpr string
			reassigned   bool
		}

		localAliases := make(map[string]*localAlias)

		// First pass over statements in blocks to find candidate short declarations
		ast.Inspect(body, func(n ast.Node) bool {
			// Inspect nested ast.FuncLit closures too (such as StateChangeConf RefreshFunc or CustomizeDiff)
			// because they capture outer client variables.
			assign, ok := n.(*ast.AssignStmt)
			if !ok {
				return true
			}

			if assign.Tok == token.ASSIGN {
				for _, lhs := range assign.Lhs {
					if id, ok := lhs.(*ast.Ident); ok {
						if la, exists := localAliases[id.Name]; exists {
							la.reassigned = true
						}
					}
				}

				return true
			}

			if assign.Tok == token.DEFINE && len(assign.Lhs) == 1 && len(assign.Rhs) == 1 {
				lhsId, ok := assign.Lhs[0].(*ast.Ident)
				if !ok || lhsId.Name == "_" {
					return true
				}

				if ta, ok := assign.Rhs[0].(*ast.TypeAssertExpr); ok && isClientsClientType(ta.Type) {
					localAliases[lhsId.Name] = &localAlias{
						stmt:         assign,
						providerExpr: slice(ta.X.Pos(), ta.X.End()),
					}
				} else if sel, ok := assign.Rhs[0].(*ast.SelectorExpr); ok && sel.Sel.Name == "Client" {
					if xId, ok := sel.X.(*ast.Ident); ok && isMetadataVarName(xId.Name) {
						localAliases[lhsId.Name] = &localAlias{
							stmt:         assign,
							providerExpr: slice(sel.Pos(), sel.End()),
						}
					}
				}
			}

			return true
		})

		// Remove candidate statements if not reassigned, otherwise rewrite `ta` to `ta.X`
		activeAliases := make(map[string]string) // varName -> providerExpr

		for name, la := range localAliases {
			assign := la.stmt.(*ast.AssignStmt)
			if la.reassigned {
				if ta, ok := assign.Rhs[0].(*ast.TypeAssertExpr); ok {
					edits = append(edits, textEdit{
						start: offset(ta.Pos()),
						end:   offset(ta.End()),
						repl:  la.providerExpr,
					})
					replacedNodes[ta] = true
				}

				activeAliases[name] = name
			} else {
				// Delete the `v := meta.(*clients.Client)` line cleanly
				sStart, sEnd := lineBounds(src, offset(assign.Pos()), offset(assign.End()))
				edits = append(edits, textEdit{start: sStart, end: sEnd, repl: ""})
				replacedNodes[assign] = true
				activeAliases[name] = la.providerExpr
			}
		}

		for pName := range paramProviders {
			activeAliases[pName] = pName
		}

		// Second pass: rewrite `<base>.<Field>` and standalone `activeAliases` identifier uses
		var walk func(n ast.Node)

		walk = func(n ast.Node) {
			if n == nil || replacedNodes[n] {
				return
			}
			// Don't re-process parameters of nested FuncLit, only their bodies
			if sel, ok := n.(*ast.SelectorExpr); ok {
				if fm, isKnown := fieldMap[sel.Sel.Name]; isKnown {
					if provExpr, matched := matchProviderBase(sel.X, isClientsClientType, activeAliases, slice); matched {
						pkgId := pkgIdentFor(fm.TargetImportPath, fm.TargetPkgName)
						edits = append(edits, textEdit{
							start: offset(sel.Pos()),
							end:   offset(sel.End()),
							repl:  fmt.Sprintf("%s.%s(%s)", pkgId, fm.HelperFuncName, provExpr),
						})
						replacedNodes[sel] = true

						return
					}
				}
				// Recurse into sel.X ONLY (never treat sel.Sel field name as a standalone variable!)
				walk(sel.X)

				return
			}

			if kv, ok := n.(*ast.KeyValueExpr); ok {
				// In CompositeLit `Foo{Key: Val}`, never rewrite `Key` if `Key` is a struct field name!
				// (Safe to walk Value always; walk Key only if not Ident)
				if _, isIdent := kv.Key.(*ast.Ident); !isIdent {
					walk(kv.Key)
				}

				walk(kv.Value)

				return
			}

			if ta, ok := n.(*ast.TypeAssertExpr); ok && isClientsClientType(ta.Type) {
				edits = append(edits, textEdit{
					start: offset(ta.Pos()),
					end:   offset(ta.End()),
					repl:  slice(ta.X.Pos(), ta.X.End()),
				})
				replacedNodes[ta] = true

				return
			}

			if id, ok := n.(*ast.Ident); ok {
				if provExpr, isAlias := activeAliases[id.Name]; isAlias && provExpr != id.Name {
					edits = append(edits, textEdit{
						start: offset(id.Pos()),
						end:   offset(id.End()),
						repl:  provExpr,
					})
					replacedNodes[id] = true
				}

				return
			}

			ast.Inspect(n, func(child ast.Node) bool {
				if child == nil || child == n {
					return true
				}

				walk(child)

				return false
			})
		}
		walk(body)
	}

	for _, decl := range file.Decls {
		if fn, ok := decl.(*ast.FuncDecl); ok {
			processFunc(fn.Type, fn.Body)
		}
	}

	if len(edits) == 0 {
		return false, nil
	}

	// Remove internal/clients import if no longer referenced anywhere in unreplaced code
	if clientsImpSpec != nil && !stillReferencesClientsPkg(file, clientsPkgIdent, replacedNodes) {
		iStart, iEnd := lineBounds(src, offset(clientsImpSpec.Pos()), offset(clientsImpSpec.End()))
		edits = append(edits, textEdit{start: iStart, end: iEnd, repl: ""})
	}

	// Insert new imports into the import block
	if len(neededImports) > 0 {
		impInsertOffset, wrapParens := findImportInsertPos(fset, file)

		var lines []string

		for impPath, alias := range neededImports {
			if alias == "" {
				lines = append(lines, fmt.Sprintf("\t%q\n", impPath))
			} else {
				lines = append(lines, fmt.Sprintf("\t%s %q\n", alias, impPath))
			}
		}

		sort.Strings(lines)

		insertStr := strings.Join(lines, "")
		if wrapParens {
			insertStr = "\nimport (\n" + insertStr + ")\n"
		}

		edits = append(edits, textEdit{start: impInsertOffset, end: impInsertOffset, repl: insertStr})
	}

	// Sort edits in reverse offset order and apply
	sort.Slice(edits, func(i, j int) bool {
		if edits[i].start != edits[j].start {
			return edits[i].start > edits[j].start
		}

		return edits[i].end > edits[j].end
	})

	out := append([]byte(nil), src...)

	lastStart := len(out) + 1
	for _, e := range edits {
		if e.end > lastStart {
			return false, fmt.Errorf("overlapping edits at [%d:%d] (lastStart=%d)", e.start, e.end, lastStart)
		}

		out = append(out[:e.start], append([]byte(e.repl), out[e.end:]...)...)
		lastStart = e.start
	}

	formatted, err := format.Source(out)
	if err != nil {
		return false, fmt.Errorf("gofmt failed: %w\n---\n%s", err, string(out))
	}

	if bytes.Equal(src, formatted) {
		return false, nil
	}

	return true, os.WriteFile(filePath, formatted, 0o644)
}

func matchProviderBase(
	x ast.Expr,
	isClientsClientType func(ast.Expr) bool,
	activeAliases map[string]string,
	slice func(token.Pos, token.Pos) string,
) (string, bool) {
	// Unwrap parens: `(meta.(*clients.Client))`
	for {
		p, ok := x.(*ast.ParenExpr)
		if !ok {
			break
		}

		x = p.X
	}

	if ta, ok := x.(*ast.TypeAssertExpr); ok && isClientsClientType(ta.Type) {
		return slice(ta.X.Pos(), ta.X.End()), true
	}

	if id, ok := x.(*ast.Ident); ok {
		if prov, exists := activeAliases[id.Name]; exists {
			return prov, true
		}
	}

	if sel, ok := x.(*ast.SelectorExpr); ok && sel.Sel.Name == "Client" {
		if xId, ok := sel.X.(*ast.Ident); ok && isMetadataVarName(xId.Name) {
			return slice(sel.Pos(), sel.End()), true
		}
	}

	return "", false
}

func isMetadataVarName(name string) bool {
	switch name {
	case "metadata", "meta", "rmd", "a", "e", "m", "v", "r", "d":
		return true
	}

	return false
}

func deriveAlias(impPath, defaultPkgName string) string {
	if impPath == accountImp {
		return "clientsAccount"
	}

	if impPath == featuresImp {
		return "providerFeatures"
	}

	parts := strings.Split(impPath, "/")
	if defaultPkgName == "client" && len(parts) >= 2 {
		svc := strings.ReplaceAll(parts[len(parts)-2], "-", "")

		return svc + "Client"
	}

	return defaultPkgName + "Pkg"
}

func collectDeclaredNames(file *ast.File) map[string]bool {
	names := make(map[string]bool)
	recordFields := func(fl *ast.FieldList) {
		if fl == nil {
			return
		}

		for _, f := range fl.List {
			for _, n := range f.Names {
				if n.Name != "_" {
					names[n.Name] = true
				}
			}
		}
	}

	ast.Inspect(file, func(n ast.Node) bool {
		switch d := n.(type) {
		case *ast.FuncDecl:
			if d.Name != nil {
				names[d.Name.Name] = true
			}

			recordFields(d.Recv)

			if d.Type != nil {
				recordFields(d.Type.Params)
				recordFields(d.Type.Results)
			}
		case *ast.FuncLit:
			if d.Type != nil {
				recordFields(d.Type.Params)
				recordFields(d.Type.Results)
			}
		case *ast.ValueSpec:
			for _, id := range d.Names {
				if id.Name != "_" {
					names[id.Name] = true
				}
			}
		case *ast.TypeSpec:
			if d.Name != nil {
				names[d.Name.Name] = true
			}
		case *ast.AssignStmt:
			if d.Tok == token.DEFINE {
				for _, lhs := range d.Lhs {
					if id, ok := lhs.(*ast.Ident); ok && id.Name != "_" {
						names[id.Name] = true
					}
				}
			}
		case *ast.RangeStmt:
			if d.Tok == token.DEFINE {
				if id, ok := d.Key.(*ast.Ident); ok && id.Name != "_" {
					names[id.Name] = true
				}

				if id, ok := d.Value.(*ast.Ident); ok && id.Name != "_" {
					names[id.Name] = true
				}
			}
		}

		return true
	})

	return names
}

func stillReferencesClientsPkg(file *ast.File, clientsIdent string, replaced map[ast.Node]bool) bool {
	found := false

	var walk func(n ast.Node)

	walk = func(n ast.Node) {
		if n == nil || found || replaced[n] {
			return
		}

		if _, isImp := n.(*ast.ImportSpec); isImp {
			return
		}

		if sel, ok := n.(*ast.SelectorExpr); ok {
			if id, ok := sel.X.(*ast.Ident); ok && id.Name == clientsIdent {
				found = true

				return
			}
		}

		ast.Inspect(n, func(child ast.Node) bool {
			if child == nil || child == n {
				return true
			}

			walk(child)

			return false
		})
	}
	for _, decl := range file.Decls {
		walk(decl)
	}

	return found
}

func lineBounds(src []byte, start, end int) (int, int) {
	s := start
	for s > 0 && src[s-1] != '\n' {
		// Only consume leading horizontal whitespace; if there's code earlier on the same line, don't eat it
		if src[s-1] != ' ' && src[s-1] != '\t' {
			return start, end
		}

		s--
	}

	e := end
	for e < len(src) && (src[e] == ' ' || src[e] == '\t' || src[e] == '\r') {
		e++
	}

	if e < len(src) && src[e] == '\n' {
		e++
	}

	return s, e
}

func findImportInsertPos(fset *token.FileSet, file *ast.File) (int, bool) {
	for _, decl := range file.Decls {
		gd, ok := decl.(*ast.GenDecl)
		if !ok || gd.Tok != token.IMPORT {
			continue
		}

		if gd.Rparen.IsValid() {
			return fset.Position(gd.Rparen).Offset, false
		}
	}

	return fset.Position(file.Name.End()).Offset, true
}
