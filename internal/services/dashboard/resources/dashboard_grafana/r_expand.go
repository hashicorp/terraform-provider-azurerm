package dashboard_grafana

import (
	"github.com/hashicorp/go-azure-helpers/lang/pointer"
	"github.com/hashicorp/go-azure-helpers/resourcemanager/identity"
	"github.com/hashicorp/go-azure-helpers/resourcemanager/location"
	"github.com/hashicorp/go-azure-sdk/resource-manager/dashboard/2025-08-01/managedgrafanas"
)

func expandCreateForDashboardGrafana(model DashboardGrafanaModel) *managedgrafanas.ManagedGrafana {
	properties := managedgrafanas.ManagedGrafana{}

	apiKey := managedgrafanas.ApiKeyDisabled
	if model.ApiKeyEnabled {
		apiKey = managedgrafanas.ApiKeyEnabled
	}

	deterministicOutboundIP := managedgrafanas.DeterministicOutboundIPDisabled
	if model.DeterministicOutboundIPEnabled {
		deterministicOutboundIP = managedgrafanas.DeterministicOutboundIPEnabled
	}

	publicNetworkAccess := managedgrafanas.PublicNetworkAccessDisabled
	if model.PublicNetworkAccessEnabled {
		publicNetworkAccess = managedgrafanas.PublicNetworkAccessEnabled
	}

	zoneRedundancy := managedgrafanas.ZoneRedundancyDisabled
	if model.ZoneRedundancyEnabled {
		zoneRedundancy = managedgrafanas.ZoneRedundancyEnabled
	}

	properties = managedgrafanas.ManagedGrafana{
		Location: pointer.To(location.Normalize(model.Location)),
		Properties: &managedgrafanas.ManagedGrafanaProperties{
			ApiKey:                            &apiKey,
			AutoGeneratedDomainNameLabelScope: &model.AutoGeneratedDomainNameLabelScope,
			GrafanaConfigurations:             expandGrafanaConfigurationsModel(model.SMTP),
			DeterministicOutboundIP:           &deterministicOutboundIP,
			GrafanaIntegrations:               expandGrafanaIntegrationsModel(model.AzureMonitorWorkspaceIntegrations),
			GrafanaMajorVersion:               &model.GrafanaMajorVersion,
			PublicNetworkAccess:               &publicNetworkAccess,
			ZoneRedundancy:                    &zoneRedundancy,
		},
		Sku: &managedgrafanas.ResourceSku{
			Name: model.Sku,
		},
		Tags: &model.Tags,
	}

	if model.SkuSize != "" {
		properties.Sku.Size = pointer.ToEnum[managedgrafanas.Size](model.SkuSize)
	}
	return &properties
}

func expandGrafanaConfigurationsModel(input []SMTPConfigurationModel) *managedgrafanas.GrafanaConfigurations {
	smtp := expandSMTPConfigurationModel(input)
	if smtp == nil {
		return nil
	}

	return &managedgrafanas.GrafanaConfigurations{Smtp: smtp}
}

func expandSMTPConfigurationModel(input []SMTPConfigurationModel) *managedgrafanas.Smtp {
	if len(input) == 0 {
		return nil
	}

	v := input[0]
	return &managedgrafanas.Smtp{
		Enabled:        pointer.To(v.SMTPEnabled),
		FromAddress:    pointer.To(v.FromAddress),
		FromName:       pointer.To(v.FromName),
		Host:           pointer.To(v.Host),
		Password:       pointer.To(v.Password),
		SkipVerify:     pointer.To(v.SkipVerify),
		User:           pointer.To(v.User),
		StartTLSPolicy: (*managedgrafanas.StartTLSPolicy)(pointer.To(v.StartTLSPolicy)),
	}
}

func expandGrafanaIntegrationsModel(inputList []AzureMonitorWorkspaceIntegrationModel) *managedgrafanas.GrafanaIntegrations {
	if len(inputList) == 0 {
		return nil
	}

	return &managedgrafanas.GrafanaIntegrations{
		AzureMonitorWorkspaceIntegrations: expandAzureMonitorWorkspaceIntegrationModelArray(inputList),
	}
}

func expandAzureMonitorWorkspaceIntegrationModelArray(inputList []AzureMonitorWorkspaceIntegrationModel) *[]managedgrafanas.AzureMonitorWorkspaceIntegration {
	outputList := make([]managedgrafanas.AzureMonitorWorkspaceIntegration, 0, len(inputList))
	for _, v := range inputList {
		input := v
		output := managedgrafanas.AzureMonitorWorkspaceIntegration{
			AzureMonitorWorkspaceResourceId: &input.ResourceId,
		}

		outputList = append(outputList, output)
	}

	return &outputList
}

func expandLegacySystemAndUserAssignedMap(input []any) *identity.LegacySystemAndUserAssignedMap {
	identityValue, err := identity.ExpandSystemOrUserAssignedMap(input)
	if err != nil {
		return nil
	}

	return &identity.LegacySystemAndUserAssignedMap{
		Type:        identityValue.Type,
		PrincipalId: identityValue.PrincipalId,
		TenantId:    identityValue.TenantId,
		IdentityIds: identityValue.IdentityIds,
	}
}
