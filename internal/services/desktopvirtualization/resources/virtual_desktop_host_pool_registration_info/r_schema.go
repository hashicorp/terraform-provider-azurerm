package virtual_desktop_host_pool_registration_info

import (
	"github.com/hashicorp/go-azure-sdk/resource-manager/desktopvirtualization/2025-10-10/hostpool"
	"github.com/hashicorp/terraform-provider-azurerm/internal/tf/pluginsdk"
	"github.com/hashicorp/terraform-provider-azurerm/internal/tf/validation"
)

func virtualDesktopHostPoolRegistrationInfoSchema() map[string]*pluginsdk.Schema {
	return map[string]*pluginsdk.Schema{
		"hostpool_id": {
			Description:  "The ID of the Virtual Desktop Host Pool to link the Registration Info to. Only a single virtual_desktop_host_pool_registration_info resource should be associated with a given hostpool. Assigning multiple resources will produce inconsistent results.",
			Type:         pluginsdk.TypeString,
			Required:     true,
			ForceNew:     true,
			ValidateFunc: hostpool.ValidateHostPoolID,
		},

		"expiration_date": {
			Description:  "A valid `RFC3339Time` for the expiration of the token.",
			Type:         pluginsdk.TypeString,
			ValidateFunc: validation.IsRFC3339Time,
			Required:     true,
		},

		"token": {
			Description: "The registration token generated by the Virtual Desktop Host Pool for registration of session hosts.",
			Type:        pluginsdk.TypeString,
			Sensitive:   true,
			Computed:    true,
		},
	}
}
