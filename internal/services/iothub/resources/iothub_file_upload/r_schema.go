package iothub_file_upload

import (
	"github.com/hashicorp/go-azure-helpers/resourcemanager/commonids"
	"github.com/hashicorp/terraform-provider-azurerm/internal/services/iothub/helpers"
	"github.com/hashicorp/terraform-provider-azurerm/internal/services/iothub/validate"
	storageValidate "github.com/hashicorp/terraform-provider-azurerm/internal/services/storage/validate"
	"github.com/hashicorp/terraform-provider-azurerm/internal/tf/pluginsdk"
	"github.com/hashicorp/terraform-provider-azurerm/internal/tf/validation"
	devices "github.com/jackofallops/kermit/sdk/iothub/2022-04-30-preview/iothub" // azignore:AZG010 - package name does not match its path
)

func (r Resource) Arguments() map[string]*pluginsdk.Schema {
	return map[string]*pluginsdk.Schema{
		"iothub_id": {
			Description:  "The ID of the IoT Hub.",
			Type:         pluginsdk.TypeString,
			Required:     true,
			ForceNew:     true,
			ValidateFunc: validate.IotHubID,
		},

		"connection_string": {
			Description:      "The connection string for the Azure Storage Account to which files are uploaded.",
			Type:             pluginsdk.TypeString,
			Required:         true,
			DiffSuppressFunc: helpers.FileUploadConnectionStringDiffSuppress,
			Sensitive:        true,
			ValidateFunc:     validation.StringIsNotEmpty,
		},

		"container_name": {
			Description:  "The name of the root container where the files should be uploaded to. The container need not exist but should be creatable using the `connection_string` specified.",
			Type:         pluginsdk.TypeString,
			Required:     true,
			ValidateFunc: storageValidate.StorageContainerName,
		},

		"authentication_type": {
			Description:  "The type used to authenticate against the Storage Account.",
			Type:         pluginsdk.TypeString,
			Optional:     true,
			Default:      string(devices.AuthenticationTypeKeyBased),
			ValidateFunc: validation.StringInEnumSlice(devices.PossibleAuthenticationTypeValues(), false),
		},

		"default_ttl": {
			Description:  "The period of time for which a file upload notification message is available to consume before it expires, specified as an [ISO 8601 timespan duration](https://en.wikipedia.org/wiki/ISO_8601#Durations). This value must be between 1 minute and 48 hours.", // azignore:AZS014 - TODO 6.0 move the range from the documentation to validation
			Type:         pluginsdk.TypeString,
			Optional:     true,
			Default:      "PT1H",
			ValidateFunc: validation.ISO8601Duration,
		},

		"identity_id": {
			Description:  "The ID of the User Managed Identity used to authenticate against the Storage Account.",
			Type:         pluginsdk.TypeString,
			Optional:     true,
			ValidateFunc: commonids.ValidateUserAssignedIdentityID,
		},

		"lock_duration": {
			Description:  "The lock duration for the file upload notifications queue, specified as an [ISO 8601 timespan duration](https://en.wikipedia.org/wiki/ISO_8601#Durations). This value must be between 5 and 300 seconds.", // azignore:AZS014 - TODO 6.0 move the range from the documentation to validation
			Type:         pluginsdk.TypeString,
			Optional:     true,
			Default:      "PT1M",
			ValidateFunc: validation.ISO8601Duration,
		},

		"max_delivery_count": {
			Description:  "The number of times the IoT Hub attempts to deliver a file upload notification message.",
			Type:         pluginsdk.TypeInt,
			Optional:     true,
			Default:      10,
			ValidateFunc: validation.IntBetween(1, 100),
		},

		"notifications_enabled": {
			Description: "Used to specify whether file notifications are sent to IoT Hub on upload.",
			Type:        pluginsdk.TypeBool,
			Optional:    true,
			Default:     false,
		},

		"sas_ttl": {
			Description:  "The period of time for which the SAS URI generated by IoT Hub for file upload is valid, specified as an [ISO 8601 timespan duration](https://en.wikipedia.org/wiki/ISO_8601#Durations). This value must be between 1 minute and 24 hours.", // azignore:AZS014 - TODO 6.0 move the range from the documentation to validation
			Type:         pluginsdk.TypeString,
			Optional:     true,
			Default:      "PT1H",
			ValidateFunc: validation.ISO8601Duration,
		},
	}
}

func (r Resource) Attributes() map[string]*pluginsdk.Schema {
	return map[string]*pluginsdk.Schema{}
}
