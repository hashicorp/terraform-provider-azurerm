package appservice

import (
	"context"
	"encoding/json"
	"fmt"
	"io"
	"net/http"
	"time"

	"github.com/hashicorp/go-azure-helpers/lang/response"
	"github.com/hashicorp/go-azure-sdk/resource-manager/web/2023-12-01/webapps"
)

const (
	// functionAppFunctionDefaultKeyName is the name of the key the Functions host creates for every Function.
	functionAppFunctionDefaultKeyName = "default"

	functionAppFunctionKeysPollInterval = 15 * time.Second
)

// listFunctionAppFunctionKeys retrieves the Function-level keys (not the Host keys) for the specified Function.
//
// The keys are generated by the Functions host once it has loaded the Function, which can take a while after the
// Function has been created/deployed. Until then the API returns no keys, so we poll until at least one key is
// returned or the context deadline is reached.
func listFunctionAppFunctionKeys(ctx context.Context, client *webapps.WebAppsClient, id webapps.FunctionId) (map[string]string, error) {
	for {
		resp, err := client.ListFunctionKeys(ctx, id)
		if err != nil {
			if response.WasNotFound(resp.HttpResponse) {
				return nil, fmt.Errorf("%s was not found", id)
			}
			return nil, fmt.Errorf("listing keys for %s: %+v", id, err)
		}

		keys, err := functionAppFunctionKeysFromResponse(resp.HttpResponse)
		if err != nil {
			return nil, fmt.Errorf("parsing keys for %s: %+v", id, err)
		}

		if len(keys) > 0 {
			return keys, nil
		}

		select {
		case <-ctx.Done():
			return nil, fmt.Errorf("waiting for keys for %s: no keys were returned before the timeout was reached. The Functions host generates keys once it has successfully loaded the Function - check that the Function App is running and that the Function's code has been deployed and is not in an error state", id)
		case <-time.After(functionAppFunctionKeysPollInterval):
		}
	}
}

// functionAppFunctionKeysFromResponse parses the raw response body of the `listKeys` API.
//
// Whilst the API Specification documents the response as a `StringDictionary` (with the keys nested within
// `properties`), the API has been observed to return the keys as a flat JSON object (e.g. `{"default": "..."}`) - as such we parse
// the raw response body here and support both shapes.
func functionAppFunctionKeysFromResponse(resp *http.Response) (map[string]string, error) {
	if resp == nil || resp.Body == nil {
		return map[string]string{}, nil
	}

	body, err := io.ReadAll(resp.Body)
	if err != nil {
		return nil, fmt.Errorf("reading response body: %+v", err)
	}

	return parseFunctionAppFunctionKeys(body)
}

func parseFunctionAppFunctionKeys(body []byte) (map[string]string, error) {
	result := make(map[string]string)
	if len(body) == 0 {
		return result, nil
	}

	raw := make(map[string]json.RawMessage)
	if err := json.Unmarshal(body, &raw); err != nil {
		return nil, fmt.Errorf("unmarshaling response body: %+v", err)
	}

	// documented shape: a `StringDictionary` with the keys nested within `properties`
	if props, ok := raw["properties"]; ok {
		nested := make(map[string]string)
		if err := json.Unmarshal(props, &nested); err != nil {
			return nil, fmt.Errorf("unmarshaling `properties`: %+v", err)
		}
		return nested, nil
	}

	// observed shape: a flat object mapping the key name to the key value
	for k, v := range raw {
		switch k {
		case "id", "kind", "name", "type":
			// ARM envelope fields, which aren't keys
			continue
		}

		var value string
		if err := json.Unmarshal(v, &value); err != nil {
			// skip any non-string values, since these can't be keys
			continue
		}
		result[k] = value
	}

	return result, nil
}
